-- V5: tabla de entrenadores (Fase 2). Entidad independiente.
-- La relación 1-1 con el equipo vive en equipo.id_entrenador (UNIQUE), ver V7__equipo.sql (RN-03).
CREATE TABLE entrenador (
    id_entrenador BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR(100) NOT NULL,
    nacionalidad  VARCHAR(60),

    CONSTRAINT pk_entrenador PRIMARY KEY (id_entrenador)
);
