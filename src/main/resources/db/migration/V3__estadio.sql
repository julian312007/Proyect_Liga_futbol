-- V3: tabla de estadios (Fase 2). Entidad independiente (D-4).
--
-- IMPORTANTE (ddl-auto=validate): en las columnas VARCHAR la longitud debe coincidir EXACTAMENTE con
-- @Column(length = ...) de la entidad Estadio. Una migración ya aplicada no se edita nunca: los cambios van
-- en una migración nueva.
CREATE TABLE estadio (
    id_estadio BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    nombre     VARCHAR(100) NOT NULL,
    ciudad     VARCHAR(100) NOT NULL,
    capacidad  INTEGER      NOT NULL,

    CONSTRAINT pk_estadio PRIMARY KEY (id_estadio),
    -- EST-03: capacidad mayor que cero.
    CONSTRAINT ck_estadio_capacidad CHECK (capacidad > 0)
);

-- EST-01: el nombre es único por ciudad sin distinguir mayúsculas (última defensa ante concurrencia; el servicio
-- además normaliza el nombre y responde 409 antes de llegar aquí).
CREATE UNIQUE INDEX ux_estadio_ciudad_nombre ON estadio (lower(ciudad), lower(nombre));
