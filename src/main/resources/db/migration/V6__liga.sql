-- V6: tabla de ligas (Fase 2). Entidad independiente.
CREATE TABLE liga (
    id_liga      BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR(100) NOT NULL,
    temporada    VARCHAR(20)  NOT NULL,
    fecha_inicio DATE         NOT NULL,
    fecha_fin    DATE         NOT NULL,

    CONSTRAINT pk_liga PRIMARY KEY (id_liga),
    CONSTRAINT uq_liga_nombre_temporada UNIQUE (nombre, temporada),
    CONSTRAINT ck_liga_fechas CHECK (fecha_fin > fecha_inicio)
);
