-- V11: tabla de tarjetas (Fase 5).
CREATE TABLE tarjeta (
    id_tarjeta BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    id_partido BIGINT      NOT NULL,
    id_jugador BIGINT      NOT NULL,
    tipo       VARCHAR(20) NOT NULL,
    minuto     INTEGER     NOT NULL,

    CONSTRAINT pk_tarjeta PRIMARY KEY (id_tarjeta),
    CONSTRAINT fk_tarjeta_partido FOREIGN KEY (id_partido) REFERENCES partido (id_partido),
    CONSTRAINT fk_tarjeta_jugador FOREIGN KEY (id_jugador) REFERENCES jugador (id_jugador),
    CONSTRAINT ck_tarjeta_minuto CHECK (minuto BETWEEN 1 AND 130),
    -- Si se agrega un tipo al enum TipoTarjeta, hay que ampliar este CHECK en una migración nueva.
    CONSTRAINT ck_tarjeta_tipo CHECK (tipo IN ('AMARILLA', 'ROJA'))
);

CREATE INDEX ix_tarjeta_partido ON tarjeta (id_partido);
CREATE INDEX ix_tarjeta_jugador ON tarjeta (id_jugador);
