-- V7: tabla de equipos (Fase 3).
CREATE TABLE equipo (
    id_equipo        BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    nombre           VARCHAR(100) NOT NULL,
    ciudad           VARCHAR(100) NOT NULL,
    anio_fundacion   INTEGER      NOT NULL,
    id_estadio_local BIGINT       NOT NULL,
    id_entrenador    BIGINT       NOT NULL,
    id_liga          BIGINT       NOT NULL,

    CONSTRAINT pk_equipo PRIMARY KEY (id_equipo),
    -- Un equipo no se repite dentro de una liga (el índice también sirve para buscar por liga).
    CONSTRAINT uq_equipo_liga_nombre UNIQUE (id_liga, nombre),
    -- RN-03: un entrenador dirige a un solo equipo (relación 1-1, FK única).
    CONSTRAINT uq_equipo_entrenador UNIQUE (id_entrenador),
    CONSTRAINT fk_equipo_estadio_local FOREIGN KEY (id_estadio_local) REFERENCES estadio (id_estadio),
    CONSTRAINT fk_equipo_entrenador FOREIGN KEY (id_entrenador) REFERENCES entrenador (id_entrenador),
    CONSTRAINT fk_equipo_liga FOREIGN KEY (id_liga) REFERENCES liga (id_liga),
    CONSTRAINT ck_equipo_anio_fundacion CHECK (anio_fundacion > 0)
);

CREATE INDEX ix_equipo_estadio_local ON equipo (id_estadio_local);
