-- V8: tabla de jugadores (Fase 3).
CREATE TABLE jugador (
    id_jugador       BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    nombre           VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE         NOT NULL,
    posicion         VARCHAR(20)  NOT NULL,
    dorsal           INTEGER      NOT NULL,
    id_equipo        BIGINT       NOT NULL,

    CONSTRAINT pk_jugador PRIMARY KEY (id_jugador),
    -- RN-02: un jugador pertenece a un solo equipo (FK NOT NULL); el dorsal es único dentro del equipo.
    CONSTRAINT uq_jugador_equipo_dorsal UNIQUE (id_equipo, dorsal),
    CONSTRAINT fk_jugador_equipo FOREIGN KEY (id_equipo) REFERENCES equipo (id_equipo),
    CONSTRAINT ck_jugador_dorsal CHECK (dorsal BETWEEN 1 AND 99),
    -- Si se agrega una posición al enum PosicionJugador, hay que ampliar este CHECK en una migración nueva.
    CONSTRAINT ck_jugador_posicion CHECK (posicion IN ('PORTERO', 'DEFENSA', 'MEDIOCAMPISTA', 'DELANTERO'))
);
