-- V2: tabla de usuarios (Fase 1: autenticación con Google).
--
-- No hay contraseñas: la identidad la prueba Google. google_sub es el identificador estable de la cuenta
-- de Google (claim "sub" del ID token) y queda nulo hasta el primer ingreso del usuario, por ejemplo en el
-- administrador inicial, que se crea solo con su correo. PostgreSQL permite varios NULL en una columna UNIQUE.
--
-- IMPORTANTE (ddl-auto=validate): Hibernate compara esta tabla con la entidad Usuario y, en las columnas
-- VARCHAR, exige que la longitud coincida EXACTAMENTE con @Column(length = ...). Si se cambia una
-- longitud aquí, hay que cambiarla también en la entidad (y al revés). Una migración ya aplicada no se
-- edita nunca: los cambios van en una migración nueva.
--
-- El correo se guarda normalizado (sin espacios y en minúsculas) por la aplicación. Las restricciones UNIQUE
-- son la última defensa ante ingresos simultáneos.
CREATE TABLE usuario (
    id_usuario     BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    -- Google documenta el sub como una cadena ASCII de hasta 255 caracteres.
    google_sub     VARCHAR(255),
    email          VARCHAR(254) NOT NULL,
    nombre         VARCHAR(100) NOT NULL,
    picture_url    VARCHAR(500),
    rol            VARCHAR(20)  NOT NULL DEFAULT 'USER',
    activo         BOOLEAN      NOT NULL DEFAULT TRUE,
    -- TIMESTAMPTZ es el tipo que Hibernate espera para java.time.Instant.
    fecha_creacion TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Nulo hasta el primer ingreso con Google.
    ultimo_acceso  TIMESTAMPTZ,

    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_google_sub UNIQUE (google_sub),
    CONSTRAINT uq_usuario_email UNIQUE (email),
    -- Si se agrega un rol al enum Rol, hay que ampliar este CHECK en una migración nueva.
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('ADMIN', 'USER'))
);
