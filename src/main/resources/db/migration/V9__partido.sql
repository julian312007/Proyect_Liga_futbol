-- V9: tabla de partidos (Fase 4).
CREATE TABLE partido (
    id_partido          BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    id_liga             BIGINT      NOT NULL,
    jornada             INTEGER     NOT NULL,
    -- TIMESTAMPTZ es el tipo que Hibernate espera para java.time.Instant.
    fecha_hora          TIMESTAMPTZ NOT NULL,
    id_equipo_local     BIGINT      NOT NULL,
    id_equipo_visitante BIGINT      NOT NULL,
    id_estadio          BIGINT      NOT NULL,
    id_arbitro          BIGINT      NOT NULL,
    goles_local         INTEGER     NOT NULL DEFAULT 0,
    goles_visitante     INTEGER     NOT NULL DEFAULT 0,
    estado              VARCHAR(20) NOT NULL DEFAULT 'PROGRAMADO',

    CONSTRAINT pk_partido PRIMARY KEY (id_partido),
    CONSTRAINT fk_partido_liga FOREIGN KEY (id_liga) REFERENCES liga (id_liga),
    CONSTRAINT fk_partido_equipo_local FOREIGN KEY (id_equipo_local) REFERENCES equipo (id_equipo),
    CONSTRAINT fk_partido_equipo_visitante FOREIGN KEY (id_equipo_visitante) REFERENCES equipo (id_equipo),
    CONSTRAINT fk_partido_estadio FOREIGN KEY (id_estadio) REFERENCES estadio (id_estadio),
    CONSTRAINT fk_partido_arbitro FOREIGN KEY (id_arbitro) REFERENCES arbitro (id_arbitro),
    -- RN-04: un equipo no se enfrenta a sí mismo.
    CONSTRAINT ck_partido_equipos_distintos CHECK (id_equipo_local <> id_equipo_visitante),
    CONSTRAINT ck_partido_jornada CHECK (jornada >= 1),
    CONSTRAINT ck_partido_goles CHECK (goles_local >= 0 AND goles_visitante >= 0),
    -- Si se agrega un estado al enum EstadoPartido, hay que ampliar este CHECK en una migración nueva.
    CONSTRAINT ck_partido_estado CHECK (estado IN ('PROGRAMADO', 'EN_JUEGO', 'FINALIZADO')),
    -- RN-06 y RN-07: última defensa (misma fecha y hora exactas). El servicio valida antes y responde 409.
    CONSTRAINT uq_partido_estadio_fecha UNIQUE (id_estadio, fecha_hora),
    CONSTRAINT uq_partido_arbitro_fecha UNIQUE (id_arbitro, fecha_hora)
);

-- Consultas frecuentes: calendario por jornada, por equipo y por estado (tabla de posiciones).
CREATE INDEX ix_partido_liga_jornada ON partido (id_liga, jornada);
CREATE INDEX ix_partido_equipo_local ON partido (id_equipo_local);
CREATE INDEX ix_partido_equipo_visitante ON partido (id_equipo_visitante);
CREATE INDEX ix_partido_liga_estado ON partido (id_liga, estado);
