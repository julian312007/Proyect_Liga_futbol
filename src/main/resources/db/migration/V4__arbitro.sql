-- V4: tabla de árbitros (Fase 2). Entidad independiente.
CREATE TABLE arbitro (
    id_arbitro        BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR(100) NOT NULL,
    nacionalidad      VARCHAR(60),
    anios_experiencia INTEGER      NOT NULL,

    CONSTRAINT pk_arbitro PRIMARY KEY (id_arbitro),
    CONSTRAINT ck_arbitro_anios_experiencia CHECK (anios_experiencia >= 0)
);
