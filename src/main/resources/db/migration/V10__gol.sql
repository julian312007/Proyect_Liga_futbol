-- V10: tabla de goles (Fase 5).
CREATE TABLE gol (
    id_gol     BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    id_partido BIGINT      NOT NULL,
    id_jugador BIGINT      NOT NULL,
    minuto     INTEGER     NOT NULL,
    tipo       VARCHAR(20) NOT NULL,

    CONSTRAINT pk_gol PRIMARY KEY (id_gol),
    CONSTRAINT fk_gol_partido FOREIGN KEY (id_partido) REFERENCES partido (id_partido),
    CONSTRAINT fk_gol_jugador FOREIGN KEY (id_jugador) REFERENCES jugador (id_jugador),
    CONSTRAINT ck_gol_minuto CHECK (minuto BETWEEN 1 AND 130),
    -- Si se agrega un tipo al enum TipoGol, hay que ampliar este CHECK en una migración nueva.
    CONSTRAINT ck_gol_tipo CHECK (tipo IN ('NORMAL', 'PENAL', 'AUTOGOL'))
);

CREATE INDEX ix_gol_partido ON gol (id_partido);
CREATE INDEX ix_gol_jugador ON gol (id_jugador);
